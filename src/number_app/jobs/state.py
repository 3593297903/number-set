TRANSITIONS={
    'CREATED':{'GENERATING','INTERRUPTED','FAILED','CANCELLED'},
    'GENERATING':{'WRITING','INTERRUPTED','FAILED','CANCELLED'},
    'WRITING':{'AUDITING','INTERRUPTED','FAILED','CANCELLED'},
    'AUDITING':{'COMMITTING','COMPLETED','FAILED','INTERRUPTED','CANCELLED','DAMAGED'},
    'COMMITTING':{'COMPLETED','INTERRUPTED','FAILED','CANCELLED'},
    'COMPLETED':{'DAMAGED','AUDITING'},
    'INTERRUPTED':{'AUDITING','FAILED','CANCELLED'},
    'FAILED':{'AUDITING','DAMAGED'},
    'CANCELLED':{'AUDITING','DAMAGED'},
    'DAMAGED':{'AUDITING'},
}

def require_transition(old,new):
    if new!=old and new not in TRANSITIONS.get(old,set()): raise ValueError(f'非法状态迁移 {old} -> {new}')
